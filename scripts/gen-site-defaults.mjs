// Copies tuition-api's site-content defaults and schemas into the web app:
//   lib/site-content-defaults.json  the copy the landing falls back to when the API is down
//   lib/site-content-schema.ts      the same zod rules, so the admin editor checks what the API checks
//   yarn gen:site-defaults          write both copies
//   yarn gen:site-defaults:check    fail when either copy is stale
// The source folder comes from SITE_CONTENT_SRC, else ../tuition-api/src/modules/site-content.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const src =
  process.env.SITE_CONTENT_SRC ?? "../tuition-api/src/modules/site-content";

const files = [
  {
    from: "defaults.json",
    to: "lib/site-content-defaults.json",
    build: (text) => JSON.stringify(JSON.parse(text), null, 2) + "\n",
  },
  {
    from: "site-content.schema.ts",
    to: "lib/site-content-schema.ts",
    // The web app has zod 3.25, which ships zod 4 under "zod/v4".
    build: (text) =>
      "// Generated by `yarn gen:site-defaults` from tuition-api. Do not edit by hand.\n\n" +
      text.replace(/from "zod";/, 'from "zod/v4";'),
  },
];

let stale = false;
for (const file of files) {
  const source = path.join(src, file.from);
  if (!existsSync(source)) {
    console.error(
      `gen:site-defaults: ${source} not found. Set SITE_CONTENT_SRC.`,
    );
    process.exit(1);
  }
  const output = file.build(readFileSync(source, "utf8"));
  if (process.argv.includes("--check")) {
    const current = existsSync(file.to) ? readFileSync(file.to, "utf8") : "";
    if (current !== output) {
      console.error(
        `${file.to} is out of date with ${source}. Run \`yarn gen:site-defaults\` and commit it.`,
      );
      stale = true;
    }
  } else {
    writeFileSync(file.to, output);
    console.log(`Wrote ${file.to} from ${source}`);
  }
}
if (stale) process.exit(1);
if (process.argv.includes("--check"))
  console.log("Site content copies are up to date.");
