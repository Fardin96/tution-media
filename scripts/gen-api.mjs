// Generates lib/api-types.ts from the backend's OpenAPI document.
//   yarn gen:api          write lib/api-types.ts
//   yarn gen:api:check    fail when lib/api-types.ts is stale
// The spec comes from OPENAPI_SPEC (a path or URL), else ../tuition-api/openapi.json.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import prettier from "prettier";

const OUT = "lib/api-types.ts";
const source = process.env.OPENAPI_SPEC ?? "../tuition-api/openapi.json";
const isUrl = /^https?:\/\//.test(source);

if (!isUrl && !existsSync(source)) {
  console.error(
    `gen:api: ${source} not found. Run \`yarn openapi:export\` in tuition-api, or set OPENAPI_SPEC.`,
  );
  process.exit(1);
}

// defaultNonNullable: false keeps fields with a server default optional in request bodies.
const ast = await openapiTS(
  isUrl ? new URL(source) : pathToFileURL(path.resolve(source)),
  { defaultNonNullable: false },
);
const banner =
  "// Generated by `yarn gen:api` from tuition-api's openapi.json. Do not edit by hand.\n\n";
const config = (await prettier.resolveConfig(OUT)) ?? {};
const output = await prettier.format(banner + astToString(ast), {
  ...config,
  filepath: OUT,
});

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== output) {
    console.error(
      `${OUT} is out of date with ${source}. Run \`yarn gen:api\` and commit it.`,
    );
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${OUT} from ${source}`);
}
